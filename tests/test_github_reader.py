def test_parse_url():
    assert parse_url("https://github.com/pallets/click/issues/3888") == ("pallets/click", 3888)
    assert parse_url("https://github.com/pallets/click/issues/3888#issuecomment-1") == ("pallets/click", 3888)
    for bad, code in [("https://gitlab.com/a/b/issues/1", "INVALID_URL"), ("http://evil.com/github.com/a/b/issues/1", "INVALID_URL"),
                      ("https://github.com/a/b/pull/2", "NOT_AN_ISSUE")]:
        with pytest.raises(GitHubError) as e:
            parse_url(bad)
        assert e.value.code == code


