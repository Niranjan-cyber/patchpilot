import json
from pathlib import Path

import pytest

from backend.github.reader import GitHubError, ai_policy, detect, expected_actual, linked_open_prs, parse_url

FX = Path("fixtures/github")
load = lambda n: json.loads((FX / n).read_text(encoding="utf-8"))


def test_parse_url():
    assert parse_url("https://github.com/pallets/click/issues/3888") == ("pallets/click", 3888)
    assert parse_url("https://github.com/pallets/click/issues/3888#issuecomment-1") == ("pallets/click", 3888)
    for bad, code in [("https://gitlab.com/a/b/issues/1", "INVALID_URL"), ("http://evil.com/github.com/a/b/issues/1", "INVALID_URL"),
                      ("https://github.com/a/b/pull/2", "NOT_AN_ISSUE")]:
        with pytest.raises(GitHubError) as e:
            parse_url(bad)
        assert e.value.code == code


def test_real_fixture_click():
    names = [x["name"] for x in load("contents_click_root.json")]
    assert detect(names, load("repo_click.json")["language"]) == (True, True)
    assert linked_open_prs(load("issue_click_timeline.json")) == []


def test_linked_open_pr_detected_but_not_closed_ones():
    tl = [{"event": "cross-referenced", "source": {"issue": {"number": 9, "state": "open", "pull_request": {}}}},
          {"event": "cross-referenced", "source": {"issue": {"number": 8, "state": "closed", "pull_request": {}}}},
          {"event": "cross-referenced", "source": {"issue": {"number": 7, "state": "open"}}}]   # an issue, not a PR
    assert linked_open_prs(tl) == [9]


def test_detect_non_python_and_no_tests():
    assert detect(["package.json", "src"], "TypeScript") == (False, False)
    assert detect(["pyproject.toml", "src"], None) == (True, False)


def test_expected_actual():
    assert expected_actual("Steps...\nExpected: ZeroDivisionError\nActual: returns 0") == ("ZeroDivisionError", "returns 0")
    assert expected_actual("no template here") == (None, None)


def test_ai_policy():
    assert ai_policy(["We do not accept pull requests generated by AI tools."]) == "forbidden"
    assert ai_policy(["AI-generated contributions are not allowed."]) == "forbidden"
    assert ai_policy(["Use of AI assistants is allowed but must be disclosed in the PR."]) == "allowed"
    assert ai_policy(["Please run the tests before opening a PR."]) == "unknown"
